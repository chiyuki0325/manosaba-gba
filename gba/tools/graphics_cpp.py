"""Emit native asset descriptors and every selected chapter's timeline into the ROM."""
from pathlib import Path
import json
from graphics_project import GBA,ContentCache,write_changed,digest,check_budget,config
from obj_silhouettes import silhouette_groups


def emit(cache_root=None,output=None):
    cache=ContentCache(cache_root);source=cache.root/'linked'
    linked=json.loads((source/'graphics.json').read_text());assets=linked['assets'];paths=sorted(linked['programs'])
    ids={key:index for index,key in enumerate(sorted(assets))}
    offsets={b['id']:b['offset'] for b in linked['blobs']}
    payload=(source/'graphics.bin').read_bytes()
    # The VM audit consumes this catalog before the optional portrait cache is built.
    preliminary=[]
    for bank,path in enumerate(paths):
        program=cache.get_json(linked['programs'][path]);chapter=json.loads((cache.root/'chapters'/(path+'.json')).read_text())
        preliminary.append(dict(path=path,bank=bank,source_sha256=chapter['source_sha256'],event_lines=program['event_lines'],source_lines=[e['line']for e in chapter['events']if e['op']=='PrintTextModified']))
    catalog_path=GBA/'assets/graphics/catalog.json'
    if not catalog_path.exists() or json.loads(catalog_path.read_text())['chapters']!=preliminary:
        write_changed(catalog_path,json.dumps(dict(chapters=preliminary,rom=linked['report']),ensure_ascii=False,indent=2)+'\n')
    from actor_cache import build as build_actor_cache,BUDGET,cached_entry_angles,large_tilt_fallbacks
    trial_bytes=sum(p.stat().st_size for p in (GBA/'assets/trial').glob('*.bin'))
    room=config()['budgets']['graphics_bytes']-linked['report']['graphics_bytes']-trial_bytes
    cached,payload,cache_report=build_actor_cache(assets,ids,offsets,payload,linked['programs'],min(BUDGET,room))
    lines=['// Generated by graphics_cpp.py; raw bytes live in assets/graphics/graphics.bin.',
           '#include "graphics_data.h"','namespace manosaba {']
    def ptr(blob,type_='uint8_t'):
        return f'graphics_bytes+{offsets[blob]}' if type_=='uint8_t' else f'reinterpret_cast<const {type_}*>(graphics_bytes+{offsets[blob]})'
    def array(type_,name,values):
        values=values or ['{}']
        lines.append(f'const {type_} {name}[]={{')
        for at in range(0,len(values),16):lines.append(','.join(map(str,values[at:at+16]))+',')
        lines.append('};')
    alpha_tiles={}
    definitions=[];regular=[]
    for key,index in ids.items():
        asset=assets[key];kind=asset['kind'];parts='nullptr';variants='nullptr';palette='nullptr';frames='nullptr';count=0;frame_count=0
        if kind=='obj':
            definitions_parts=[]
            groups=silhouette_groups(asset['parts'],payload,offsets,alpha_tiles)
            for p,part in enumerate(asset['parts']):
                array('uint32_t',f'a{index}_p{p}_tiles',[offsets[t] for t in part['tiles']])
                definitions_parts.append('{'+f'a{index}_p{p}_tiles,{part["x"]},{part["y"]},{part["width"]},{part["height"]},{part["bank"]},{groups[p]}'+'}')
            array('graphic_part',f'a{index}_parts',definitions_parts)
            parts=f'a{index}_parts';palette=ptr(asset['palette'],'uint16_t');count=len(asset['parts'])
        elif kind in ('bg','mask'):
            source_variants=asset['variants']+asset.get('base_variants',[]) if kind=='bg' else asset['frames'];items=[]
            for v,variant in enumerate(source_variants):
                array('uint32_t',f'a{index}_v{v}_tiles',[offsets[t] | (0x80000000 if kind=='bg' and all(payload[offsets[t]:offsets[t]+64]) else 0) for t in variant['tiles']])
                mapping=ptr(variant['map']) if variant['map'] else 'nullptr'
                items.append('{'+f'a{index}_v{v}_tiles,{mapping},{variant.get("affine_count",len(variant["tiles"]))},{variant.get("scale",256)}'+'}')
            array('graphic_variant',f'a{index}_variants',items);variants=f'a{index}_variants';count=len(asset['variants']) if kind=='bg' else len(items)
            if kind=='bg':
                palette=ptr(asset['palette'],'uint16_t')
                if asset.get('regular'):
                    r=asset['regular'];regular.append('{'+f'{ptr(r["map"],"uint16_t")},{index},{r["count"]},{r["columns"]},{r["origin"]}'+'}')
                if asset.get('obj_frames'):
                    array('uint16_t',f'a{index}_obj_frames',[ids[frame] for frame in asset['obj_frames']]);frames=f'a{index}_obj_frames';frame_count=len(asset['obj_frames'])
        elif kind=='animation':
            array('uint16_t',f'a{index}_frames',[ids[frame] for frame in asset['frames']]);frames=f'a{index}_frames';frame_count=len(asset['frames'])
        width,height=asset.get('size',[asset.get('width',240),asset.get('height',160)])
        pivot=asset.get('pivot',[width//2,height//2])
        color=0
        if kind in ('solid','rectangle'):
            channels=bytes.fromhex(asset['color'].lstrip('#'));color=(channels[0]>>3)|((channels[1]>>3)<<5)|((channels[2]>>3)<<10)
        definitions.append('{'+','.join(map(str,[parts,variants,palette,frames,width,height,count,frame_count,len(asset.get('base_variants',[])),*pivot,f'graphic_kind::{kind}',asset.get('fps',0),color]))+'}')
    for item in cached:
        a=item['asset'];index=item['image'];prefix=f'cache_{index}'
        rows=[]
        for p,part in enumerate(a['parts']):
            array('uint32_t',f'{prefix}_p{p}_tiles',part['tiles'])
            rows.append('{'+f'{prefix}_p{p}_tiles,{part["x"]},{part["y"]},{part["width"]},{part["height"]},{part["bank"]},0'+'}')
        array('graphic_part',f'{prefix}_parts',rows)
        definitions.append('{'+f'{prefix}_parts,nullptr,reinterpret_cast<const uint16_t*>(graphics_bytes+{a["palette"]}),nullptr,{a["width"]},{a["height"]},{len(a["parts"])},0,0,{a["pivot"][0]},{a["pivot"][1]},graphic_kind::obj,0,{a["baked_angle"]&65535},{a["nominal_scale"]}'+'}')
    array('graphic_asset','graphic_assets',definitions)
    array('graphic_regular','graphic_regular_images',regular)
    lines.append(f'const int graphic_regular_count={len(regular)};')
    from cg_regular_policy import appearances
    appearance_flags=appearances(cache,paths,ids,linked['programs'])
    array('graphic_cache_entry','graphic_cache_entries',['{'+','.join(str(v[k])for k in('base','image','scale','angle','phase_x','phase_y','coverage_key'))+'}'for v in cached])
    lines.append(f'const int graphic_cache_entry_count={len(cached)};')
    banks=[];catalog=[]
    for bank,path in enumerate(paths):
        program=cache.get_json(linked['programs'][path]);resources=program['resources']
        entry_angles=cached_entry_angles(program,ids,cached);fallbacks=large_tilt_fallbacks(program,assets,ids,cached);keys=list(program['keys'])
        command_rows=[];event_rows=[]
        for event_index,event in enumerate(program['events']):
            begin=len(command_rows)
            for command_index in range(event[0],event[0]+event[1]):
                value,first,count,kind,target,prop,flags=program['commands'][command_index]
                if command_index in fallbacks:
                    first=len(keys);keys.append(fallbacks[command_index])
                elif command_index in entry_angles:
                    value_,_,ease,relative=keys[first];first=len(keys);keys.append([value_,0,ease,relative])
                if kind==0:value=ids[resources[value]]
                command_rows.append('{'+f'{value},{first},{count},stage_kind({kind}),{target},{prop},{flags}'+'}')
            for target,regular in sorted(appearance_flags.get(bank,{}).get(event_index,{}).items()):
                command_rows.append('{'+f'{int(regular)},0,0,stage_kind::cg_backend,{target},0,0'+'}')
            event_rows.append('{'+f'{begin},{len(command_rows)-begin},{event[2]}'+'}')
        array('stage_command',f'b{bank}_commands',command_rows)
        array('stage_key',f'b{bank}_keys',['{'+f'{v},{frames},stage_ease({ease}),{relative}'+'}' for v,frames,ease,relative in keys])
        array('stage_event',f'b{bank}_events',event_rows)
        mask_ids=[-1]*8
        for mask,key in program.get('mask_resources',{}).items():mask_ids[int(mask)]=ids[key]
        array('int16_t',f'b{bank}_masks',mask_ids)
        banks.append('{'+f'{json.dumps(path)},b{bank}_commands,b{bank}_keys,b{bank}_events,b{bank}_masks,{len(program["events"])}'+'}')
        catalog.append(dict(path=path,bank=bank,source_sha256=json.loads((cache.root/'chapters'/(path+'.json')).read_text())['source_sha256'],
                            event_lines=program['event_lines'],source_lines=[e['line'] for e in json.loads((cache.root/'chapters'/(path+'.json')).read_text())['events'] if e['op']=='PrintTextModified']))
    array('graphics_bank','graphics_banks',banks)
    lines.append(f'const int graphics_bank_count={len(paths)},graphic_asset_count={len(ids)+len(cached)};\n}}')
    write_changed(GBA/'src/graphics_data.cpp','#ifdef MANOSABA_ACTOR_BAKED\n#include "../build-actor-baked/graphics_data.inc"\n#else\n'+'\n'.join(lines)+'\n#endif\n')
    write_changed(GBA/'assets/graphics/graphics.bin',payload)
    write_changed(GBA/'src/graphics_bytes.s','// Payload SHA256: '+digest(payload)+'\n.section .rodata.graphics_bytes,"a",%progbits\n.balign 4\n.global _ZN8manosaba14graphics_bytesE\n_ZN8manosaba14graphics_bytesE:\n.ifdef MANOSABA_ACTOR_BAKED\n.incbin "../build-actor-baked/graphics.bin"\n.else\n.incbin "../assets/graphics/graphics.bin"\n.endif\n')
    cache_bytes=cache_report['payload_bytes']+cache_report['directory_bytes']
    final_report=dict(linked['report'],**check_budget(linked['report']['graphics_bytes']+cache_bytes))
    final_report.update(payload_bytes=len(payload),assets=len(ids)+len(cached),actor_cache_bytes=cache_bytes,cached_variants=len(cached))
    write_changed(GBA/'assets/graphics/catalog.json',json.dumps(dict(chapters=catalog,rom=final_report),ensure_ascii=False,indent=2)+'\n')
    return dict(chapters=len(paths),assets=len(ids),payload_bytes=len(payload),cached_variants=len(cached),cache_bytes=cache_report['payload_bytes']+cache_report['directory_bytes'])

if __name__=='__main__':print(emit())
