"""Court BG resources and crop-only references into the game's existing portrait dictionary."""
from collections import Counter
import json,math
import numpy as np
from graphics_project import GBA,ContentCache,config,write_changed,digest
from trial_story import ACTORS
from trial_camera import catalog as camera_catalog,PAN_WIDTH
from trial_views import catalog as view_catalog,reduced_view
from trial_pose_assets import select as select_poses
from court_render import backgrounds,encode_backgrounds,cropped_pieces,placements,actors as demo_actors,VIEW_SETTINGS,FORMAL_VIEW_SETTINGS
from encode_gba_graphics import train_family,encode_actor
from graphics_archive import build_archive
from graphics_cpp import emit


def main():
    cache=ContentCache();imported=json.loads((cache.root/'import.json').read_text())['assets']
    encoded=json.loads((cache.root/'encoded.json').read_text());programs=json.loads((cache.root/'programs.json').read_text())
    counts=Counter()
    for key in programs.values():counts.update(cache.get_json(key)['resources'])
    pose_report=select_poses(cache,imported,encoded,programs)
    chosen=[];changed=False
    for who in ACTORS:
        candidates=[a for a in imported.values() if a.get('who')==who and a['kind'] in ('sprite','character')]
        existing=[a for a in candidates if a['id'] in encoded and encoded[a['id']]['kind']=='obj']
        if existing:asset=max(existing,key=lambda a:counts[a['id']])
        elif candidates:
            asset=candidates[0];family=train_family(candidates,cache);encoded[asset['id']]=encode_actor(asset,family,cache);changed=True
        else:raise ValueError('Missing shared trial portrait: '+who)
        chosen.append(encoded[asset['id']])
    write_changed(cache.root/'encoded.json',json.dumps(encoded,ensure_ascii=False,sort_keys=True)+'\n')
    linked=json.loads((cache.root/'linked/graphics.json').read_text())
    if changed or not set(pose_report['selected'])<=linked['assets'].keys():
        build_archive(cache,encoded,programs,project=config(),extra_resources=pose_report['selected']);emit()
    linked=json.loads((cache.root/'linked/graphics.json').read_text());ids={key:i for i,key in enumerate(sorted(linked['assets']))}
    images,depths=backgrounds(cache)
    formal_images,formal_depths=backgrounds(cache,FORMAL_VIEW_SETTINGS,cache.root/'court/formal')
    palette,bgs=encode_backgrounds(images+formal_images,cache.root/'court/backgrounds',write_expected=False)
    camera=camera_catalog();pan_depths=[];pan_settings=[]
    focal=PAN_WIDTH/math.tau;fov=math.degrees(2*math.atan(80/focal))
    distance=14.8-focal*2.8/70
    for stage in ('Court','Court_Final'):
        setting=(PAN_WIDTH,distance,4.2,0,0,True,fov);pan_settings.append(setting)
        output=cache.root/'court/camera'/stage
        pan_images,stage_depths=backgrounds(cache,[setting],output,stage=stage);pan_depths.append(stage_depths)
        _,pan_bgs=encode_backgrounds(pan_images,output,existing_palette=palette);bgs+=pan_bgs
        write_changed(GBA/'assets/trial/camera'/stage/'expected.bin',(output/'expected.bin').read_bytes())
    reduced_positions=[];forbidden=[]
    for stage,count in (('Court',13),('Court_Final',14)):
        settings=[(320,distance,height,yaw,0,False,30)
                  for distance,height in ((10,5.2),(12,5.5),(13,5.6))
                  for yaw in (0,.1*360/count,-.1*360/count)]
        output=cache.root/'court/reduced'/stage
        views,view_depths=backgrounds(cache,settings,output,stage=stage)
        _,encoded_views=encode_backgrounds(views,output,existing_palette=palette);bgs+=encoded_views
        write_changed(GBA/'assets/trial/reduced'/stage/'expected.bin',(output/'expected.bin').read_bytes())
        positions=[]
        for index,(setting,depths_for_view) in enumerate(zip(settings,view_depths)):
            _,distance,height,yaw,_,_,_=setting
            angle=math.radians(-yaw);depth=16*math.cos(angle)-distance
            focal=160/(2*math.tan(math.radians(15)))
            x=round(160+focal*16*math.sin(angle)/depth)
            y=round(80-(6.65-height)*focal/depth)
            scale=(256,320,384)[index//3]
            desktop=np.flatnonzero(depths_for_view[:,min(319,max(0,x))]<depth)
            cutoff=min(160,int(desktop[0])-16+8) if len(desktop) else 160
            positions.append((x,y,cutoff,scale))
            mask=depths_for_view[16:176,40:280]<depth;inside=mask.copy()
            for dy in range(-2,3):
                for dx in range(-2,3):inside&=np.roll(mask,(dy,dx),(0,1))
            forbidden.append(inside.astype(np.uint8).tobytes())
        reduced_positions.append(positions)
    write_changed(GBA/'assets/trial/reduced/podium-forbidden.bin',b''.join(forbidden))
    data=bytearray();lines=['// Generated by trial_stage_assets.py; portraits refer to graphics_data.cpp.','#include "trial_data.h"','namespace manosaba {']
    def add(raw):data.extend(bytes((-len(data))%4));offset=len(data);data.extend(raw);return offset
    def ptr(offset,kind='uint8_t'):return f'trial_bytes+{offset}' if kind=='uint8_t' else f'reinterpret_cast<const {kind}*>(trial_bytes+{offset})'
    pal=ptr(add(palette),'uint16_t');rows=[]
    for tiles,banks,cols in bgs:rows.append('{'+f'{ptr(add(tiles),"uint32_t")},{ptr(add(banks))},{cols}'+'}')
    lines.append(f'const uint16_t* const trial_bg_palette={pal};')
    lines.append('const trial_bg_asset trial_backgrounds[]={'+','.join(rows)+'};')
    lines.append('const trial_view_placement trial_view_positions[2][9]={'+','.join('{'+','.join('{'+','.join(map(str,p))+'}' for p in row)+'}' for row in reduced_positions)+'};')
    profile_rows=[]
    for i,asset in enumerate(chosen):
        row=[]
        profiles=placements([(ACTORS[i],asset)],formal_depths+[depths[3]],cache,
                            settings=FORMAL_VIEW_SETTINGS+[VIEW_SETTINGS[3]],scales=(176,176,176,160),clip_lower_body=True)
        for view,entries in enumerate(profiles):
            p=entries[0];bottom=p['bottom'];pieces=p['pieces']
            assert len(pieces)<=64,(ACTORS[i],view,len(pieces))
            name=f'cast_{i}_{view}';lines.append(f'const trial_actor_piece {name}[]={{'+(','.join('{'+','.join(str(part[k]) for k in ('part','x','y','width','height'))+'}' for part in pieces) or '{}')+'};')
            row.append('{'+f'{ptr(add(bottom.tobytes()),"int16_t")},{name},{p["x"]},{p["y"]},{p["scale"]},{len(pieces)}'+'}')
        profile_rows.append('{'+','.join(row)+'}')
    lines.append('const uint16_t trial_actor_images[]={'+','.join(str(ids[a['id']]) for a in chosen)+'};')
    lines.append('const trial_actor_placement trial_actor_positions[17][4]={'+','.join(profile_rows)+'};')
    pan_profiles=[];pan_sizes=[];pan_counts=[]
    for stage in range(2):
        rows=[];sizes=[];counts=[]
        for actor,asset in enumerate(chosen):
            p=placements([(ACTORS[actor],asset)],pan_depths[stage],cache,settings=[pan_settings[stage]],scales=(176,),clip_lower_body=True,seats=[0])[0][0]
            name=f'pan_{stage}_{actor}';pieces=p['pieces']
            lines.append(f'const trial_actor_piece {name}[]={{'+','.join('{'+','.join(str(part[k]) for k in ('part','x','y','width','height'))+'}' for part in pieces)+'};')
            rows.append('{'+f'{ptr(add(p["bottom"].tobytes()),"int16_t")},{name},1024,{p["y"]},{p["scale"]},{len(pieces)}'+'}')
            sizes.append(sum(p['width']*p['height']*32 for p in pieces));counts.append(len(pieces))
        pan_profiles.append('{'+','.join(rows)+'}');pan_sizes.append(sizes);pan_counts.append(counts)
    lines.append('const trial_actor_placement trial_pan_positions[2][17]={'+','.join(pan_profiles)+'};')
    layouts=[]
    for i,layout in enumerate(camera['layouts']):
        name=f'seats_{i}';lines.append(f'const uint8_t {name}[]={{'+','.join(map(str,layout['seats']))+'};')
        layouts.append('{'+f'{name},{layout["count"]},{layout["stage"]+7}'+'}')
    lines.append('const trial_camera_layout trial_camera_layouts[]={'+','.join(layouts)+'};')
    full=view_catalog();full_by_source={(m['path'],m['line']):m for m in full['motions']}
    motion_rows=[]
    for m in camera['motions']:
        source=full_by_source[(m['path'],m['line'])];count=camera['layouts'][m['layout']]['count']
        actor=camera['layouts'][m['layout']]['seats'][round(source['start']['rotation'][1]*count/360)%count]
        motion_rows.append([m[k] for k in ('start','end','frames','layout','ease')]+[reduced_view(source['start'],count),reduced_view(source['end'],count),3 if m['kind']=='yaw' else 0,0,actor])
    remaining=[]
    for missing in camera['unmapped']:
        m=full_by_source[(missing['path'],missing['line'])];layout=m['layout'];count=camera['layouts'][layout]['count']
        rise=max(-8,min(8,round((m['end']['height']-m['start']['height'])*8)))
        actor=camera['layouts'][layout]['seats'][m['seat']%count]
        start=round(904+m['start']['rotation'][1]/360*PAN_WIDTH);end=round(904+m['end']['rotation'][1]/360*PAN_WIDTH)
        mode=2 if abs(end-start)>64 else 1
        motion_rows.append([start,end,m['frames'],layout,2,reduced_view(m['start'],count),reduced_view(m['end'],count),mode,rise,actor])
        remaining.append(dict(m,motion=len(motion_rows)-1,policy='horizontal pan then endpoint cut' if mode==2 else 'representative start view, small BG vertical scroll and actor scaling, then endpoint cut'))
    lines.append('const trial_camera_motion trial_camera_motions[]={'+','.join('{'+','.join(map(str,row))+'}' for row in motion_rows)+'};')
    report={k:v for k,v in camera.items() if k!='lookup'}
    report['source_counts']=report['counts'];report['source_compound']=report['unmapped'];report['unmapped']=[]
    report['counts']=dict(total=len(motion_rows),close_pan=69,pan=9,reduced_compound=len(remaining))
    report.update(width=PAN_WIDTH,tile_bytes_by_actor=pan_sizes,obj_count_by_actor=pan_counts)
    report.update(reduced_compound=remaining,representative_views=18,representative_width=320,view_positions=reduced_positions,policy='distance 10/12/13, left/centre/right, tilt merged; short yaw retains close view; compound motion approximated')
    write_changed(GBA/'assets/trial/camera.json',json.dumps(report,ensure_ascii=False,indent=2)+'\n')
    seed=demo_actors(cache);demo=placements(seed,depths,cache);rows=[]
    for view,row in enumerate(demo):
        entries=[]
        for actor,p in enumerate(row):
            name=f'demo_{view}_{actor}';pieces=p['pieces']
            lines.append(f'const trial_actor_piece {name}[]={{'+(','.join('{'+','.join(str(s[k]) for k in ('part','x','y','width','height'))+'}' for s in pieces) or '{}')+'};')
            entries.append('{'+f'{ptr(add(p["bottom"].tobytes()),"int16_t")},{name},{p["x"]},{p["y"]},{p["scale"]},{len(pieces)}'+'}')
        rows.append('{'+','.join(entries)+'}')
    lines.append('const uint16_t trial_demo_images[]={'+','.join(str(ids[a['id']]) for _,a in seed)+'};')
    lines.append('const trial_actor_placement trial_demo_positions[4][3]={'+','.join(rows)+'};')
    lines.append('const trial_actor_placement trial_empty_position={nullptr,nullptr,0,0,256,0};\n}')
    target=GBA/'assets/trial';target.mkdir(parents=True,exist_ok=True);write_changed(target/'court.bin',bytes(data))
    pose_rows=[]
    for row in pose_report['references']:
        who=row['who'];base=who if who in ACTORS else who.removeprefix('Creature')
        if base in ACTORS:pose_rows.append(dict(path=row['path'],line=row['line'],actor=ACTORS.index(base),image=ids[row['selected']],exact=row['exact']))
    pose_summary={key:value for key,value in pose_report.items() if key not in ('mapping','references')}
    pose_summary['references']=pose_rows
    write_changed(target/'poses.json',json.dumps(pose_summary,ensure_ascii=False,sort_keys=True)+'\n')
    write_changed(GBA/'src/trial_data.cpp','\n'.join(lines)+'\n')
    write_changed(GBA/'src/trial_bytes.s','// '+digest(bytes(data))+'\n.section .rodata.trial_bytes,"a",%progbits\n.balign 4\n.global _ZN8manosaba11trial_bytesE\n_ZN8manosaba11trial_bytesE:\n.incbin "../assets/trial/court.bin"\n')
    print('shared Court resources:',len(data),'bytes; portraits:',len(chosen),'using existing game tile dictionary',flush=True)


if __name__=='__main__':main()
