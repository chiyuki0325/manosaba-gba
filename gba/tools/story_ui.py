"""Generate the shared dialogue decorations independently of chapter image assets."""
import struct
from PIL import Image
from graphics_project import GBA, ROOT, write_changed
from image_encoding import UI_COLORS, tiles


def decoration():
    ui = Image.new('P', (240, 160), 0)
    ui.putpalette(sum((list(c) for c in UI_COLORS), []) + [0]*720)
    assets = [('NormalPrinter_Frame_Bottom', (240,75), (0,85)),
              ('NormalPrinter_Frame_Top', (26,43), (214,0)),
              ('NormalPrinter_Grass_1', (27,27), (0,133)),
              ('NormalPrinter_Grass_2', (23,27), (214,133)),
              ('BookButton', (17,15), (3,3)), ('MenuButton', (17,17), (220,2))]
    for name, size, pos in assets:
        image = Image.open(ROOT/'manosaba-web/public/UI_Adv'/f'{name}.png').convert('RGBA').resize(size, Image.Resampling.LANCZOS)
        for y in range(image.height):
            for x in range(image.width):
                r,g,b,a = image.getpixel((x,y))
                if a >= 128:
                    ui.putpixel((x+pos[0],y+pos[1]), 7+min(4,(r+g+b)//140))
    # Reserved text tiles must stay empty for the live dialogue panel.
    assert not any(ui.crop((80,0,120,8)).tobytes())
    return tiles(ui,4)


def main():
    words = struct.unpack('<4800I', decoration())
    lines = ['// Generated by tools/story_ui.py.', '#include "story_ui_data.h"',
             'namespace manosaba {', 'alignas(4) const uint32_t story_ui_tiles[]={']
    for at in range(0,len(words),16):
        lines.append(','.join(map(str,words[at:at+16]))+',')
    lines.append('};\n}\n')
    write_changed(GBA/'src/story_ui_data.cpp','\n'.join(lines))


if __name__ == '__main__':
    main()
