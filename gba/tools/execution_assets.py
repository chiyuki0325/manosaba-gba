"""Small 4bpp phone and reversible fill-word patches; rotation stays offline."""
from build_paths import generated_path
from functools import cache
import json,struct
from PIL import Image,ImageDraw
from font import read_font
from graphics_project import GBA,ROOT,write_changed
from image_encoding import quantized,tiles,rgb555
from witch_book_icons import key_icon

COLORS=[(0,0,0),(8,8,8),(24,24,24),(40,40,40),(64,64,64),(88,88,88),(120,120,120),(160,160,160),(200,200,200),(232,232,224),(248,248,240),(136,48,64),(176,64,88),(88,32,40),(232,192,192),(208,200,184)]
ART=ROOT/'manosaba-web/public/UI_ExecutionButton'

@cache
def font_data():return read_font()

def glyphs(im,text,x,y,color):
    font=font_data();draw=ImageDraw.Draw(im)
    for ch in text:
        width=6 if ord(ch)<128 else 12
        for dy,bits in enumerate(font[ord(ch)]):
            for dx in range(width):
                if bits&(1<<(11-dx)):draw.point((x+dx,y+dy),fill=color)
        x+=width

def indexed(im):
    p=quantized(im,COLORS);alpha=im.getchannel('A')
    return mask(p,alpha)

def mask(p,alpha):
    data=bytearray(p.tobytes())
    for i,a in enumerate(alpha.tobytes()):data[i]=0 if a<128 else data[i] or 1
    p.frombytes(bytes(data));return p

def button(level,pressed=False,checked=False):
    im=Image.new('RGBA',(40,40))
    base=Image.open(ART/'ExecutionButton_Base.png').convert('RGBA').resize((40,40),Image.Resampling.LANCZOS);im.alpha_composite(base)
    blood=Image.new('RGBA',(40,40));d=ImageDraw.Draw(blood);d.ellipse((0,0,39,39),fill=(138,51,67,255))
    if level<40:ImageDraw.Draw(blood).rectangle((0,0,39,39-level),fill=(0,0,0,0))
    im.alpha_composite(blood);im.alpha_composite(Image.open(ART/'ExecutionButton_Frame.png').convert('RGBA').resize((40,40),Image.Resampling.LANCZOS))
    glyphs(im,'处刑',8,13,(248,248,240,255))
    if checked:
        check=Image.open(ART/'ExecutionButton_CheckIcon.png').convert('RGBA').resize((9,12),Image.Resampling.LANCZOS);im.alpha_composite(check,(17,25))
    if pressed:im=im.resize((38,38),Image.Resampling.LANCZOS)
    im=im.rotate(8,Image.Resampling.BICUBIC,expand=True)
    out=Image.new('RGBA',(56,56));out.alpha_composite(im,((56-im.width)//2+4,(56-im.height)//2));return out

def main():
    base=Image.new('RGBA',(240,160));phone=Image.open(ART/'SmartphoneBase.png').convert('RGBA').resize((77,129),Image.Resampling.LANCZOS).rotate(8,Image.Resampling.BICUBIC,expand=True)
    base.alpha_composite(phone,((240-phone.width)//2,8))
    key=key_icon('A');key=key.crop(key.getbbox())
    base.alpha_composite(key,(240-6-key.width,160-6-key.height))
    phone_base=base.copy();base.alpha_composite(button(0),(88,48));p=indexed(base)
    raw=tiles(p,4);words=struct.unpack('<4800I',raw);base_words=[0]*8
    for y in range(20):
        for x in range(8,22):base_words.extend(words[(y*30+x)*8:(y*30+x+1)*8])
    for y in range(17,20):
        for x in range(27,30):base_words.extend(words[(y*30+x)*8:(y*30+x+1)*8])
    buttons=[];patches=[];changes=[]
    def frame(level,pressed=False,checked=False):
        # Button replaces its region, including the unchanged phone beneath it.
        result=phone_base.copy();result.alpha_composite(button(level,pressed,checked),(88,48))
        return struct.unpack('<392I',tiles(indexed(result).crop((88,48,144,104)),4))
    for pressed in (False,True):
        previous=frame(0,pressed);buttons.append(previous);rows=[]
        for level in range(1,41):
            current=frame(level,pressed);start=len(changes)
            for index,(a,b) in enumerate(zip(previous,current)):
                if a!=b:
                    tile,row=divmod(index,8);word=((6+tile//7)*30+11+tile%7)*8+row
                    changes.append((word,a,b))
            rows.append((start,len(changes)-start));previous=current
        patches.append(rows)
    lines=['// Generated by tools/execution_assets.py.','#include "execution_data.h"','namespace manosaba {']
    lines+=['const uint16_t execution_colors[16]={'+','.join(str(rgb555(c)) for c in COLORS)+'};']
    def array(name,values):lines.append('const uint32_t '+name+'={'+','.join(map(str,values))+'};')
    array('execution_base[]',base_words)
    lines.append('const uint32_t execution_buttons[2][392]={'+','.join('{'+','.join(map(str,v))+'}' for v in buttons)+'};')
    array('execution_check[392]',frame(40,False,True))
    lines.append('const execution_patch execution_patches[2][execution_steps]={'+','.join('{'+','.join('{%d,%d}'%r for r in rows)+'}' for rows in patches)+'};')
    lines.append('const execution_change execution_changes[]={'+','.join('{%d,%d,%d}'%r for r in changes)+'};\n}')
    write_changed(GBA/'src/execution_data.cpp','\n'.join(lines)+'\n')
    out=generated_path('design/execution');out.mkdir(parents=True,exist_ok=True)
    for name,level,checked in [('idle',0,False),('charging',22,False),('complete',40,True)]:
        im=Image.new('RGBA',(240,160),(32,24,32,255));im.alpha_composite(phone_base);im.alpha_composite(button(level,False,checked),(88,48));indexed(im).convert('RGB').resize((720,480),Image.Resampling.NEAREST).save(out/(name+'.png'))
    report=dict(tiles=290,vram_bytes=290*32+2048,rom_bytes=len(base_words)*4+2*392*4+392*4+len(changes)*12+80*4,changes=len(changes),hold_frames=400,decay_units_per_frame=8,delay_frames=96,source_rotation_degrees=8,button_center_x=120,key_margin_right=6,key_margin_bottom=6)
    write_changed(out/'budget.json',json.dumps(report,indent=2)+'\n');print(report)
if __name__=='__main__':main()
