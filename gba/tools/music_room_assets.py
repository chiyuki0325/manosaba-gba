"""Build the approved music-room titles, stable collection links and shared texture."""
from pathlib import Path
import csv,json,struct
from PIL import Image
from image_encoding import tiles,rgb555
from music_cues import cue_key
from music_room_mockups import background

GBA=Path(__file__).resolve().parents[1]
def write(path,value):
    if not path.exists() or path.read_text()!=value:path.write_text(value)

def main():
    catalog=json.loads((GBA/'assets/music/catalog.json').read_text())
    runtime=json.loads((GBA/'assets/music/runtime.json').read_text())
    with (GBA/'assets/music/room-titles.tsv').open(encoding='utf-8-sig',newline='') as source:titles=list(csv.DictReader(source,delimiter='\t'))
    rows=[];links={}
    for title in titles:
        identity=title['曲目标识'];name=title['曲名'];index=next(i for i,e in enumerate(catalog) if e['id']==identity);entry=catalog[index]
        assert identity!='Bgm047' and entry.get('asset') and not identity.startswith('Ambi')
        bit=49 if identity=='Bgm027_002' else 50 if identity=='Song001' else 51 if identity=='Song004' else int(identity[3:])-1
        assert sum(6 if ord(c)<128 else 12 for c in name)<=184,(identity,name)
        logical=entry.get('logical_id',identity)
        packed=next(e for e in runtime['entries'] if e['id']==logical and e['asset']==entry['asset'])
        for alias in [packed['id']]+packed.get('aliases',[]):
            for variant in packed.get('variants',[1]):
                key=cue_key(f'{alias[:-3]}_{int(alias[-3:])}_{variant}')
                assert key not in links or links[key]==bit
                links[key]=bit
        rows.append(dict(id=identity,title=name,catalog=index,bit=bit))
    assert len({r['bit'] for r in rows})==len(rows)
    image=background();pixels=[rgb555(tuple(p)) for p in zip(*[iter(image.tobytes())]*3)]
    ui=[(24,24,24),(232,224,216),(176,168,160),(232,160,176),(56,44,50),(104,80,88),(64,56,56),(112,104,104),(40,32,40),(208,200,192),(248,248,240),(0,0,0)]
    palette=[rgb555(c) for c in ui]
    for color in sorted(set(pixels)):
        if color not in palette:palette.append(color)
    assert len(palette)<=16
    indexed=Image.new('P',(240,160));lookup={v:i for i,v in enumerate(palette)};indexed.putdata([lookup[p] for p in pixels])
    raw=tiles(indexed,4);pool=[];lookup={};cells=[]
    for at in range(0,len(raw),32):
        block=raw[at:at+32]
        if block not in lookup:lookup[block]=len(pool);pool.append(block)
        cells.append(lookup[block])
    palette+=[0]*(16-len(palette))
    words=struct.unpack('<'+'I'*(len(pool)*8),b''.join(pool))
    cpp=['// Generated by tools/music_room_assets.py.','#include "music_room_data.h"','namespace manosaba {',
         'static const uint16_t colors[16]={'+','.join(map(str,palette))+'};',
         'static const uint32_t texture[]={'+','.join(map(str,words))+'};',
         'static const uint16_t cells[600]={'+','.join(map(str,cells))+'};',
         'const ui_pattern music_room_background={colors,texture,cells};',
         'const music_room_track music_room_tracks[]={']
    cpp+=['{'+json.dumps(r['title'],ensure_ascii=False)+','+str(r['catalog'])+','+str(r['bit'])+'},' for r in rows]
    cpp+=['};','const int music_room_count=sizeof(music_room_tracks)/sizeof(music_room_tracks[0]);',
          'struct collection_link {uint32_t key;uint8_t bit;};',
          'static const collection_link collection_links[]={'+','.join('{%d,%d}'%(k,v) for k,v in sorted(links.items()))+'};',
          'int music_collection_bit(uint32_t key)','{','    key&=~(1u<<25);',
          '    for(const auto& link:collection_links)if(link.key==key)return link.bit;','    return -1;','}','}']
    write(GBA/'src/music_room_data.cpp','\n'.join(cpp)+'\n')
    out=GBA/'assets/music-room';out.mkdir(exist_ok=True)
    write(out/'catalog.json',json.dumps(dict(tracks=rows,texture_tiles=len(pool),texture_bytes=len(pool)*32+1200+32,links=len(links),global_music_bytes=8,bpp=4),ensure_ascii=False,indent=2)+'\n')
    print('Music room:',len(rows),'tracks,',len(pool)*32+1232,'texture/map/palette bytes')

if __name__=='__main__':main()
