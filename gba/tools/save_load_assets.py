"""Two shared 16-color native save/load backgrounds and small existing key artwork."""
import gzip,json,re,struct,zlib
from pathlib import Path
import numpy as np
from PIL import Image
from save_load_mockups import base,nine_patch
from witch_book_icons import key_icon

GBA=Path(__file__).resolve().parents[1]
COLORS=[(24,24,24),(248,248,240),(208,200,192),(248,128,168),(64,32,48),(216,56,88),(0,0,0),(16,16,16),
        (40,32,40),(56,48,48),(72,56,64),(96,80,80),(120,104,104),(176,160,152),(248,128,168),(216,56,88)]
def write(path,data):
    if isinstance(data,str):data=data.encode()
    if not path.exists() or path.read_bytes()!=data:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
def encode(image):
    rgba=np.asarray(image.convert('RGBA'));rgb=rgba[:,:,:3].astype(np.int32)
    colors=np.asarray(COLORS,dtype=np.int32)
    result=((rgb[:,:,None,:]-colors[None,None,:,:])**2).sum(axis=3).argmin(axis=2).astype(np.uint8)
    result[rgba[:,:,3]<128]=0
    return result
def tile(data):
    ordered=data.reshape(20,8,30,8).transpose(0,2,1,3).reshape(-1,2)
    return (ordered[:,0]|ordered[:,1]<<4).tobytes()
def main():
    payload=bytearray();offsets=[]
    for pause in (True,False):
        image=base()
        for box in ([(18,49,204,85)] if pause else [(8,34,222,50),(8,88,222,50)]):nine_patch(image,box)
        offsets.append(len(payload));payload.extend(tile(encode(image)))
    lines=['// Generated by save_load_assets.py.','#include "save_ui_data.h"','namespace manosaba {']
    palette=[(r//8)|((g//8)<<5)|((b//8)<<10) for r,g,b in COLORS]+[0]*240
    lines.append('const uint16_t save_ui_palette[256]={'+','.join(map(str,palette))+'};')
    lines.append('const uint32_t* const save_ui_backgrounds[2]={'+','.join('reinterpret_cast<const uint32_t*>(save_ui_bytes+'+str(o)+')' for o in offsets)+'};')
    keys=[]
    for key in 'ABLR':
        image=key_icon(key);name='save_key_'+key;pixels=encode(image).tobytes()
        lines.append('const uint8_t '+name+'[]={'+','.join(map(str,pixels))+'};');keys.append('{'+name+f',{image.width},{image.height}'+'}')
    lines.append('const save_key_art save_ui_keys[4]={'+','.join(keys)+'};')
    big={}
    with gzip.open(GBA/'assets/unifont-17.0.03.hex.gz','rt') as source:
        for line in source:
            cp,bits=line.strip().split(':')
            if chr(int(cp,16)) in '暂停存读':big[chr(int(cp,16))]=[int(bits[i:i+4],16) for i in range(0,64,4)]
    lines.append('const uint16_t save_ui_initials[4][16]={'+','.join('{'+','.join(map(str,big[c]))+'}' for c in '暂停存读')+'};')
    for stage in ('Court','Court_Final'):
        image=Image.open(GBA/f'assets/graphics-cache/court/reduced/{stage}/view-4-gba.png').convert('RGB');image.thumbnail((48,24),Image.Resampling.LANCZOS)
        preview=Image.new('RGB',(48,24),(24,24,24));preview.paste(image,((48-image.width)//2,(24-image.height)//2))
        indexed=preview.quantize(colors=15,method=Image.Quantize.MEDIANCUT);pal=indexed.getpalette()[:45];pal+=([0]*(45-len(pal)))
        native=[0]+[(pal[i]//8)|((pal[i+1]//8)<<5)|((pal[i+2]//8)<<10) for i in range(0,45,3)]
        lines.append('const uint8_t save_thumb_'+stage+'[]={'+','.join(str(x+1) for x in indexed.tobytes())+'};')
        lines.append('const uint16_t save_palette_'+stage+'[]={'+','.join(map(str,native))+'};')
    lines.append('const save_thumb_art save_court_thumbs[2]={{save_thumb_Court,save_palette_Court},{save_thumb_Court_Final,save_palette_Court_Final}};')
    catalog=json.loads((GBA/'assets/graphics-cache/linked/graphics.json').read_text())
    raw=(GBA/'assets/graphics-cache/linked/graphics.bin').read_bytes();blobs={b['id']:b['offset'] for b in catalog['blobs']};previews=[]
    for index,key in enumerate(sorted(catalog['assets'])):
        asset=catalog['assets'][key]
        if asset['kind']!='bg':continue
        variant=asset['variants'][0];mapping=raw[blobs[variant['map']]:blobs[variant['map']]+4096];hist=np.zeros(112,dtype=np.int32)
        for y in range(24):
            for x in range(48):
                px=x*5+136;py=y*160//24+176;tile_key=variant['tiles'][mapping[py//8*64+px//8]]
                hist[raw[blobs[tile_key]+py%8*8+px%8]]+=1
        chosen=[]
        for i in range(15):
            best=int(hist.argmax());chosen.append(best);hist[best]=0
        colors=np.asarray(struct.unpack_from('<112H',raw,blobs[asset['palette']]),dtype=np.int32)
        rgb=np.stack((colors&31,(colors>>5)&31,colors>>10),axis=1)
        lookup=(((rgb[:,None,:]-rgb[np.asarray(chosen)][None,:,:])**2).sum(axis=2).argmin(axis=1)+1).astype(np.uint8)
        while len(payload)%4:payload.append(0)
        at=len(payload);payload.extend(lookup.tobytes());pal=len(payload);payload.extend(struct.pack('<16H',0,*colors[chosen]))
        previews.append('{'+f'{index},save_ui_bytes+{at},reinterpret_cast<const uint16_t*>(save_ui_bytes+{pal})'+'}')
    lines.append('const save_preview_colors save_background_colors[]={'+','.join(previews)+'};')
    lines.append(f'const int save_background_count={len(previews)};')
    story=(GBA/'src/story_data.cpp').read_text();encoded=re.search(r'story_bytes\[\] = \{(.*?)\};',story,re.S)[1]
    signature=zlib.crc32(b'save-v3-music-restart'+bytes(map(int,re.findall(r'\d+',encoded))))
    signature=zlib.crc32(json.dumps(sorted(catalog['assets'])).encode(),signature)
    lines.append(f'const uint32_t save_content_signature={signature};');lines.append('}')
    write(GBA/'src/save_ui_data.cpp','\n'.join(lines)+'\n')
    write(GBA/'src/save_ui_bytes.s','.section .rodata.save_ui_bytes,"a",%progbits\n.balign 4\n.global _ZN8manosaba13save_ui_bytesE\n_ZN8manosaba13save_ui_bytesE:\n.incbin "../assets/save-ui.bin"\n')
    write(GBA/'assets/save-ui.bin',payload)
    print('save/load artwork:',len(payload),'shared base bytes, 16 UI colors')
if __name__=='__main__':main()
