"""Generate the small runtime cue table from the reviewed music manifest."""
import json
import argparse
from pathlib import Path
import re
import struct

GBA = Path(__file__).resolve().parents[1]


def cue_key(alias, exact_part=False):
    match = re.fullmatch(r'(Bgm|Song|Ambi)_?(\d+)(?:_(\d+))?(?:_(Intro|Loop))?', alias)
    if not match:
        return None
    kind, number, variant, part = match.groups()
    return int(number) | (int(variant or 1) << 12) | ((kind == 'Song') << 24) | ((kind == 'Ambi') << 26) | ((exact_part and part == 'Intro') << 25)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--audit',type=Path,help='optional diagnostic output directory')
    args=parser.parse_args()
    manifest = json.loads((GBA/'assets/music/runtime.json').read_text())
    entries = json.loads((GBA/'assets/music/catalog.json').read_text())
    titles = {e['id']: e.get('usage_note', e['title']) for e in entries}
    cues = []
    headers={}
    for entry in manifest['entries'] + manifest['part_overrides']:
        asset=entry['asset']
        if asset not in headers:
            with (GBA/'audio'/f'{asset}.xm').open('rb') as source:
                header=source.read(80)
            headers[asset]=struct.unpack_from('<3H',header,64)
        for logical in [entry['id']] + entry.get('aliases', []):
            for variant in entry.get('variants', [1]):
                alias = f'{logical[:-3]}_{int(logical[-3:])}_{variant}'
                if entry.get('part'):
                    alias += '_' + entry['part']
                cues.append(dict(alias=alias, asset=entry['asset'], title=next((e.get('usage_note',e['title']) for e in entries if e.get('logical_id',e['id'])==entry['id'] and e.get('asset')==entry['asset']),titles[entry['id']]),
                                 volume=entry['volume'], intro_order=entry['intro_order'],
                                 story_order=entry['intro_order'] if entry.get('part') else entry.get('story_default_order',entry['intro_order']),
                                 loop_order=entry['direct_loop_order'],
                                 restart_order=headers[entry['asset']][1]))
    modules = sorted({cue['asset'] for cue in cues})
    for asset in modules:
        length, restart, channels = headers[asset]
        assert channels <= 16, (asset, channels)
        for cue in cues:
            if cue['asset'] == asset:
                assert 0 <= cue['intro_order'] < length
                assert 0 <= cue['loop_order'] < length
                assert cue['restart_order'] == restart
    lines = ['// Generated by tools/music_cues.py from assets/music/runtime.json.',
             '#include "music_cues.h"', 'namespace manosaba {',
             'const music_cue music_cues[] = {']
    keys = set()
    for cue in cues:
        key = cue_key(cue['alias'], exact_part=True)
        assert key and key not in keys
        keys.add(key)
        values = [str(key), json.dumps(cue['alias']), json.dumps(cue['title'], ensure_ascii=False),
                  str(cue['volume']), str(modules.index(cue['asset'])),
                  str(cue['intro_order']), str(cue['loop_order']), str(cue['story_order'])]
        lines.append('    {' + ', '.join(values) + '},')
    lines += ['};', 'const int music_cue_count = sizeof(music_cues) / sizeof(music_cues[0]);',
              f'const int music_hiro_index = {next(i for i,c in enumerate(cues) if cue_key(c["alias"]) == cue_key("Bgm_37_2"))};',
              'const music_cue* find_music_cue(unsigned key)', '{',
              '    for(const music_cue& cue : music_cues) if(cue.key == key) return &cue;',
              '    return nullptr;', '}', '}']
    # A fused module can declare a source cue from another number as its Intro.
    # The ordinary/default order remains the body; no runtime sequencing state.
    lines.pop()
    parameters='unsigned key,unsigned intro' if manifest.get('intro_links') else 'unsigned,unsigned'
    lines += [f'int music_intro_order({parameters})', '{']
    for link in manifest.get('intro_links', []):
        key, intro = cue_key(link['path']), cue_key(link['intro'])
        entry = next(c for c in cues if cue_key(c['alias']) == key)
        data = (GBA/'audio'/f"{entry['asset']}.xm").read_bytes()
        assert intro in keys and 0 <= link['order'] < struct.unpack_from('<H',data,64)[0]
        lines.append(f"    if(key=={key} && intro=={intro})return {link['order']};")
    lines += ['    return -1;', '}', '}']
    (GBA/'src/music_cues.cpp').write_text('\n'.join(lines)+'\n')
    (GBA/'src/music_modules.inc').write_text('// Generated by tools/music_cues.py.\n'+
                                           ''.join(f'MUSIC_MODULE({name})\n' for name in modules))
    lines = ['// Generated by tools/music_cues.py.', '#include "music_catalog.h"',
             '#include "bn_music_items.h"', 'namespace manosaba {',
             'const music_entry music_catalog[] = {']
    for entry in entries:
        asset = entry.get('asset')
        label = entry.get('label_id',entry['id']) + ' - ' + entry.get('demo_title',entry.get('usage_note', entry['title']))
        detail = entry.get('description', '已制作' if asset else '未制作')
        # The user elected to use the available arrangement for every variant.
        detail = re.sub(r'；?\([12]\)未制作', '', detail)
        detail = detail.replace('版本待确认', '共用当前版')
        if entry.get('loop'):
            detail = '[循]' + detail
        variant = entry.get('source_variant', 1)
        logical=entry.get('logical_id',entry['id'])
        alias = f'{logical[:-3]}_{int(logical[-3:])}_{variant}'
        module = f'bn::music_items::{asset}.id()' if asset else '-1'
        values = [json.dumps(label, ensure_ascii=False), json.dumps(detail, ensure_ascii=False),
                  module, str(entry.get('volume', 768)), str(entry.get('loop', False)).lower(),
                  str(entry.get('start_order', 0)), json.dumps(alias)]
        lines.append('    {' + ', '.join(values) + '},')
    lines += ['};', 'const int music_count = sizeof(music_catalog) / sizeof(music_catalog[0]);',
              f'const int music_default_index = {next(i for i,e in enumerate(entries) if e["id"] == "Bgm019")};', '}']
    (GBA/'src/music_catalog.cpp').write_text('\n'.join(lines)+'\n')
    # Preserve the exact contexts of every source cue still awaiting production.
    missing = []
    if not args.audit:
        print(f'Music: {len(modules)} modules, {len(cues)} cues')
        return
    args.audit.mkdir(parents=True,exist_ok=True)
    covered = []
    for path in sorted((GBA.parent/'story/zh-Hans').rglob('*.json')):
        doc = json.loads(path.read_text())
        for event in doc.get('events', []):
            if event['op'] != 'PlayBgm':
                continue
            params = event['params']
            alias = params.get('BgmPath')
            if not isinstance(alias, str):
                continue
            entry = dict(path=doc['path'], line=event['line'], alias=alias,
                         intro=params.get('IntroBgmPath'))
            (covered if cue_key(alias) in keys else missing).append(entry)
    missing_music=[event for event in missing if not event['alias'].startswith('Ambi')]
    report = dict(modules=len(modules), cues=len(cues), covered_events=len(covered),
                  unpacked_events=len(missing), unpacked_music_events=len(missing_music),
                  ambience_outside_bgm_events=len(missing)-len(missing_music),covered=covered,unpacked=missing)
    (args.audit/'cue_coverage.json').write_text(json.dumps(report, ensure_ascii=False, indent=2)+'\n')
    print(f'Music: {len(modules)} modules, {len(cues)} exact cues, {len(covered)} covered PlayBgm events; {len(missing_music)} unpacked music events; {len(missing)-len(missing_music)} ambience events outside BGM bus')


if __name__ == '__main__':
    main()
