"""Pack original credits into ROM text/line tables, without slides or new glyphs."""
from pathlib import Path
import json,re,struct
from ending_roll_research import source,pack,width
from graphics_project import GBA,ContentCache,write_changed
from font import read_font
from story_layout import reflow

HEADING=1;CENTER=2;FAST=4

def build():
    ui=source(ContentCache());master=json.loads((GBA/'assets/source-metadata/trial.json').read_text())['master']
    titles=json.loads((GBA/'assets/ending-roll-titles-zh.json').read_text())
    titles.update({'作詞・作曲・編曲':'作词·作曲·编曲','歌唱':'演唱','Guitar':'吉他','Mix':'混音','ストーリーパート':'故事部分','裁判パート':'审判部分'})
    characters={}
    for actor in master['AuthorData']['_items']:
        names={e['_locale']:re.sub('<[^>]*>','',e['_text']) for e in actor['_taggedText']}
        if names.get(0) and names.get(2):characters[names[0]]=names[2]
    def translate(row):
        text=row['text'].replace('（ストーリーパート）','（故事部分）').replace('（裁判パート）','（审判部分）')
        return characters.get(text,titles.get(text,text)) if row['path'].endswith('LabelLeft') else titles.get(text,text)
    def section(labels):
        rows=[];i=0
        def line(text,flags=CENTER):
            for value in reflow(text,216).split('\n'):rows.append((value,flags))
        while i<len(labels):
            row=labels[i];text=translate(row);i+=1
            if '/Roll_' in row['path']:
                if rows:rows.append(('',0))
                line(text,HEADING|CENTER);rows.append(('',0))
            elif row['path'].endswith('LabelLeft') and i<len(labels) and labels[i]['path'].rsplit('/',1)[0]==row['path'].rsplit('/',1)[0] and labels[i]['path'].endswith('LabelRight'):
                right=translate(labels[i]);i+=1
                if '\n' not in text+right and width(text+'  '+right)<=216:line(text+'  '+right)
                else:line(text);line(right)
            else:line(text)
        return rows
    act1=section([r for r in ui['labels'] if '/Act1/ScrollView/Viewport/Content/' in r['path']])
    staff2=section([r for r in ui['labels'] if '/Act2/ScrollViews/View_1/Viewport/Content/Left/' in r['path']])
    final2=section([r for r in ui['labels'] if '/Act2/ScrollViews/View_5/' in r['path']])
    thanks=master['SpecialThanksData'];packed=[];names=0
    for group in thanks['_textSizeByCourses']:
        entries=[next(n['_text'] for n in item['_name'] if n['_locale']==0) for item in thanks['_items'] if item['_course']==group['_course']]
        names+=len(entries);packed.extend((s,FAST) for s in pack(entries));packed.append(('',FAST))
    act2=staff2+[('',0),('特别鸣谢',HEADING|CENTER),('',0)]+packed+[('',0)]+final2
    # Blank lead/tail rows allow the first/last names to enter and leave naturally.
    datasets=[[('',0)]*12+rows+[('',0)]*12 for rows in (act1,act2)]
    blob=bytearray();offsets={};tables=[];glyphs=set()
    for rows in datasets:
        encoded=[]
        for text,flags in rows:
            assert width(text)<=216,(text,width(text))
            glyphs.update(text)
            if text not in offsets:offsets[text]=len(blob);blob.extend(text.encode()+b'\0')
            encoded.append(offsets[text]|flags<<24)
        tables.append(encoded)
    out=GBA/'assets/ending-roll';out.mkdir(exist_ok=True)
    write_changed(out/'text.bin',bytes(blob))
    lines=['// Generated by tools/ending_roll_assets.py.','#include "credits_data.h"','namespace manosaba {']
    for i,table in enumerate(tables):lines+=['static const uint32_t rows'+str(i)+'[]={'+','.join(map(str,table))+'};']
    lines+=['const credits_entry credits_entries[]={']
    for i,table in enumerate(tables):lines+=['{rows'+str(i)+','+str(len(table))+'},']
    lines+=['};','}'];write_changed(GBA/'src/credits_data.cpp','\n'.join(lines)+'\n')
    write_changed(GBA/'src/credits_bytes.s','.section .rodata\n.balign 4\n.global credits_text\ncredits_text:\n.incbin "../assets/ending-roll/text.bin"\n')
    available=read_font();write_changed(GBA/'src/ending_glyphs.txt',''.join(sorted(c for c in glyphs if ord(c) in available)))
    report=dict(staff_rows=[len(act1),len(staff2)],total_rows=[len(r) for r in datasets],names=names,thanks_rows=len(packed),text_bytes=len(blob),line_bytes=sum(len(t)*4 for t in tables),
                missing_glyphs=[f'U+{ord(c):04X}' for c in sorted(glyphs) if ord(c) not in available],characters=characters,background=['black','white'],shadow=['1px dark gray','1px ecru'],select=False)
    write_changed(out/'catalog.json',json.dumps(report,ensure_ascii=False,indent=2)+'\n');print('Ending roll:',report)

if __name__=='__main__':build()
