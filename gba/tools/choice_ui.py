#!/usr/bin/env python3
"""Resize the original choice artwork to a 240x160, 256-color opaque UI."""
from pathlib import Path
from collections import Counter
import json
from PIL import Image, ImageEnhance
import numpy as np

from story_layout import clean_text, pixel_width

GBA=Path(__file__).resolve().parents[1]
ROOT=GBA.parent
ART=ROOT/'manosaba-web/public/UI_Adv'
WIDTH,HEIGHT=208,40
TEXT_LEFT,TEXT_BAD_LEFT,TEXT_RIGHT=44,56,196


def artwork():
    # Flatten the original translucent texture once, freeing the entire scene
    # allocation while choices are visible. Runtime performs no alpha blending.
    base=Image.new('RGBA',(240,160),(64,64,64,255))
    base.alpha_composite(Image.open(ART/'Choice/ChoiceScreenBase.png').convert('RGBA').resize(base.size,Image.Resampling.LANCZOS))
    for name,size,at in [('BookButton',(17,15),(3,3)),('MenuButton',(17,17),(220,2))]:
        base.alpha_composite(Image.open(ART/(name+'.png')).convert('RGBA').resize(size,Image.Resampling.LANCZOS),at)
    buttons=[]
    for bad in (False,True):
        for selected in (False,True):
            button=Image.new('RGBA',(WIDTH,HEIGHT))
            name='ChoicesFrame_Highlighted' if selected else 'ChoiceFrame_Default'
            button.alpha_composite(Image.open(ART/'Choice'/(name+'.png')).convert('RGBA').resize((WIDTH,36),Image.Resampling.LANCZOS),(0,2))
            if bad:
                icon=Image.open(ART/'Choice/DangerNotice.png').convert('RGBA').resize((24,30),Image.Resampling.LANCZOS)
                sharp=ImageEnhance.Sharpness(icon.convert('RGB')).enhance(1.8)
                contrast=ImageEnhance.Contrast(sharp).enhance(1.4).convert('RGBA')
                contrast.putalpha(icon.getchannel('A'))
                button.alpha_composite(contrast,(18,5))
            buttons.append(button)
    return base,buttons


def encode(images):
    samples=[]
    for im in images:
        data=im.tobytes()
        samples.extend(tuple(v&248 for v in data[i:i+3]) for i in range(0,len(data),4) if data[i+3]>=128)
    sample=Image.new('RGB',(len(samples),1));sample.putdata(samples)
    trained=sample.quantize(colors=253,method=Image.Quantize.MEDIANCUT).getpalette()[:759]
    colors=[(0,0,0)]*256
    colors[1]=(248,248,240);colors[6]=(0,0,0)
    chosen=[];seen={colors[1],colors[6]}
    # RGB555 can collapse several trained RGB888 colors. Fill those slots with
    # distinct native colors instead of wasting the expanded choice palette.
    candidates=[tuple(v&248 for v in rgb) for rgb in zip(*[iter(trained)]*3)]
    candidates.extend(rgb for rgb,_ in Counter(samples).most_common())
    for rgb in candidates:
        if rgb not in seen:chosen.append(rgb);seen.add(rgb)
        if len(chosen)==253:break
    for at,rgb in zip((i for i in range(256) if i not in (0,1,6)),chosen):colors[at]=rgb
    palette=np.asarray(colors[1:],dtype=np.int16)//8
    encoded=[]
    for im in images:
        rgba=np.asarray(im)
        unique,inverse=np.unique((rgba[:,:,:3]>>3).reshape(-1,3),axis=0,return_inverse=True)
        delta=unique.astype(np.int16)[:,None,:]-palette[None,:,:]
        lookup=(delta*delta).sum(axis=2).argmin(axis=1)+1
        pixels=lookup[inverse];pixels[rgba[:,:,3].reshape(-1)<128]=0
        words=[]
        for ty in range(im.height//8):
            for tx in range(im.width//8):
                for y in range(8):
                    for half in range(2):
                        words.append(sum(int(pixels[(ty*8+y)*im.width+tx*8+half*4+x])<<(x*8) for x in range(4)))
        encoded.append(words)
    return colors,encoded


def validate_options():
    paths={c['path'] for c in json.loads((GBA/'assets/graphics/catalog.json').read_text())['chapters']}
    count=maximum=0
    for path in sorted(paths):
        if '_Trial' in path:continue  # Trial uses its own multi-line choice bubbles.
        for event in json.loads((ROOT/'story/zh-Hans'/(path+'.json')).read_text())['events']:
            if event['op']!='AddChoice':continue
            p=event['params'];label=clean_text(p['ChoiceSummary'])
            left=TEXT_BAD_LEFT if p.get('ButtonPath')=='ChoiceButtons/Adv/Bad' else TEXT_LEFT
            width=pixel_width(label)
            assert '\n' not in label and width<=TEXT_RIGHT-left,(path,event['line'],label,width)
            count+=1;maximum=max(maximum,width)
    return count,maximum


def write(path,text):
    if not path.exists() or path.read_text()!=text:path.write_text(text)


def main():
    count,maximum=validate_options()
    base,buttons=artwork();colors,encoded=encode([base,*buttons])
    header='''// Generated by tools/choice_ui.py from the original UI_Adv/Choice artwork.
#ifndef CHOICE_UI_DATA_H
#define CHOICE_UI_DATA_H
#include <cstdint>
namespace manosaba {
constexpr int choice_button_width=208,choice_button_height=40,choice_button_left=16;
constexpr int choice_text_left=44,choice_text_bad_left=56,choice_text_right=196;
extern const uint16_t choice_ui_palette[256];
extern const uint32_t choice_ui_background[9600];
extern const uint32_t choice_ui_buttons[4][2080];
}
#endif
'''
    lines=['// Generated by tools/choice_ui.py.','#include "choice_ui_data.h"','namespace manosaba {']
    palette=[(r>>3)|((g>>3)<<5)|((b>>3)<<10) for r,g,b in colors]
    lines.append('const uint16_t choice_ui_palette[256]={'+','.join(map(str,palette))+'};')
    def rows(words):return ['    '+','.join(f'0x{w:08x}' for w in words[at:at+8])+',' for at in range(0,len(words),8)]
    lines+=['const uint32_t choice_ui_background[9600]={',*rows(encoded[0]),'};','const uint32_t choice_ui_buttons[4][2080]={']
    for words in encoded[1:]:lines+=['{',*rows(words),'},']
    lines+=['};','}']
    write(GBA/'src/choice_ui_data.h',header);write(GBA/'src/choice_ui_data.cpp','\n'.join(lines)+'\n')
    print(f'choice UI: 256 colors, {WIDTH}x36 art in {WIDTH}x{HEIGHT} rows, {count} labels checked, longest {maximum}px, {sum(len(e)*4 for e in encoded)+512} ROM bytes')


if __name__=='__main__':main()
