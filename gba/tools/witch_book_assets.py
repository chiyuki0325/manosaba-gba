"""Cached book UI/portraits/maps. Evidence pixels remain in trial_ui.bin."""
from build_paths import generated_path
import csv
import gzip
import json
import struct
import numpy as np
from PIL import Image
from graphics_project import ROOT, GBA, ContentCache, digest, write_changed
from image_encoding import rgb555, tiles
from nameplates import nameplate_base, nameplate_palette
from story import compress
from trial_ui import native_palette, indexed, tile_bytes
from witch_book_catalog import BookCatalog
from witch_book_icons import key_icon

ART = ROOT/'manosaba-web/public/UI_WitchBook_1'


def main():
    cache = ContentCache()
    master = json.loads((GBA/'assets/source-metadata/trial.json').read_text())['master']
    book = BookCatalog(master, lambda key: 0)
    ui = [(0,0,0),(248,248,240),(208,200,192),(248,144,168),
          (104,56,64),(136,120,112),(0,0,0),(48,40,40),
          (248,144,168),(56,48,48),(40,32,32),(80,72,72)]+nameplate_palette()
    paper = Image.open(ART/'Background_1.png').convert('RGB').resize((240,160),Image.Resampling.LANCZOS)
    colors = ui+native_palette([paper],16)
    pixels = indexed(paper, colors, 16, False)-16
    common = bytearray(tiles(Image.fromarray(pixels),4))
    stamps = []
    for name in ('EvidenceFrame','PersonFrame'):
        image = Image.open(ART/(name+'.png')).convert('RGBA').resize((92,93),Image.Resampling.LANCZOS)
        stamps.append((len(common),92,93))
        common.extend(indexed(image,colors,16).tobytes())
    diamond = np.asarray(nameplate_base()).astype(np.uint8)
    stamps.append((len(common),52,25));common.extend(diamond.tobytes())
    for key in 'ABLR':
        image=key_icon(key)
        stamps.append((len(common),image.width,image.height))
        common.extend(indexed(image,colors,1).tobytes())
    blob=bytearray()
    lines=['// Generated by witch_book_assets.py.','#include "witch_book_art.h"','namespace manosaba {']
    def add(raw):
        blob.extend(bytes((-len(blob))%4));offset=len(blob);blob.extend(raw);return offset
    def ptr(offset,kind='uint8_t'):
        value=f'witch_book_bytes+{offset}'
        return value if kind=='uint8_t' else f'reinterpret_cast<const {kind}*>({value})'
    def blocks(raw):
        rows=[]
        for first in range(0,len(raw),4096):
            part=raw[first:first+4096];packed=compress(part);codec=len(packed)<len(part)
            rows.append('{'+ptr(add(packed if codec else part))+','+str(int(codec))+'}')
        return rows
    lines.append('const ui_picture_block book_shared_blocks[]={'+','.join(blocks(bytes(common)))+'};')
    lines.append('const book_stamp book_stamps[7]={'+','.join('{'+','.join(map(str,s))+'}' for s in stamps)+'};')
    lines.append('const uint16_t book_page_palette[32]={'+','.join(str(rgb555(c)) for c in colors)+'};')
    entries=[];cached=0
    manifest=list(csv.DictReader((ROOT/'original_sprites/manifest.csv').open()))
    profiles={r['name'][8:]:ROOT/'original_sprites'/r['output'] for r in manifest
              if r['type']=='Texture2D' and r['name'].startswith('Profile_')}
    source_images=[]
    for entry,value in enumerate(book.entries):
        if value['kind']==1:
            source_images.append((entry,profiles[value['id']],(128,128)))
    for entry,path,size in source_images:
        key=digest(dict(step='witch-book-images-v1',source=cache.file_key(path),size=size,ui=ui))
        result=cache.get_json(key)
        if result:cached+=1
        else:
            image=Image.open(path).convert('RGBA');image.thumbnail(size,Image.Resampling.LANCZOS)
            x=(240-image.width)//2;y=(160-image.height)//2
            image_colors=colors+native_palette([image],224)
            pixels=np.zeros((160,240),np.uint8)
            pixels[y:y+image.height,x:x+image.width]=indexed(image,image_colors,32)
            raw=tile_bytes(pixels);parts=[]
            for offset in range(0,len(raw),4096):
                chunk=raw[offset:offset+4096];packed=compress(chunk);codec=len(packed)<len(chunk)
                parts.append(dict(data=cache.put_blob(packed if codec else chunk),codec=int(codec)))
            result=dict(palette=cache.put_blob(struct.pack('<256H',*[rgb555(c) for c in image_colors])),
                        blocks=parts,rect=[x,y,image.width,image.height])
            cache.put_json(key,result)
        palette_ptr=ptr(add(cache.path(result['palette'],'.bin').read_bytes()),'uint16_t')
        block_rows=['{'+ptr(add(cache.path(v['data'],'.bin').read_bytes()))+','+str(v['codec'])+'}' for v in result['blocks']]
        name=f'book_image_{entry}_blocks'
        lines.append(f'const ui_picture_block {name}[]={{'+','.join(block_rows)+'};')
        entries.append('{'+str(entry)+',{'+palette_ptr+',nullptr,'+name+'},'+','.join(map(str,result['rect']))+'}')
    lines.append('const book_image book_images[]={'+','.join(entries)+'};')
    lines.append(f'const int book_image_count={len(entries)};')
    initials={ord(v['name'][0]) for v in book.texts if v['name']}|set(map(ord,'证人地规记'))
    glyphs=[]
    with gzip.open(GBA/'assets/unifont-17.0.03.hex.gz','rt') as font:
        for line in font:
            code,bits=line.strip().split(':')
            if int(code,16) in initials:
                if len(bits)==32:bits=''.join(bits[i:i+2]+'00' for i in range(0,32,2))
                glyphs.append('{'+str(int(code,16))+',{'+','.join(str(int(bits[i:i+4],16)) for i in range(0,64,4))+'}}')
    lines.append('const book_initial book_initials[]={'+','.join(glyphs)+'};')
    lines.append(f'const int book_initial_count={len(glyphs)};\n}}')
    header='''// Generated by witch_book_assets.py.
#ifndef WITCH_BOOK_ART_H
#define WITCH_BOOK_ART_H
#include "ui_picture.h"
namespace manosaba {
struct book_stamp {uint16_t offset;uint8_t width,height;};
struct book_image {uint16_t entry;ui_picture image;uint8_t x,y,width,height;};
struct book_initial {uint32_t code;uint16_t rows[16];};
extern const uint8_t witch_book_bytes[];
extern const ui_picture_block book_shared_blocks[];
extern const book_stamp book_stamps[7];
extern const uint16_t book_page_palette[32];
extern const book_image book_images[];
extern const int book_image_count;
extern const book_initial book_initials[];
extern const int book_initial_count;
constexpr int book_shared_size=SHARED_SIZE;
}
#endif
'''.replace('SHARED_SIZE',str(len(common)))
    write_changed(GBA/'src/witch_book_art.h',header)
    write_changed(GBA/'src/witch_book_art.cpp','\n'.join(lines)+'\n')
    write_changed(GBA/'assets/trial/book.bin',bytes(blob))
    write_changed(GBA/'src/witch_book_bytes.s','// '+digest(bytes(blob))+'\n.section .rodata.witch_book_bytes,"a",%progbits\n.balign 4\n.global _ZN8manosaba16witch_book_bytesE\n_ZN8manosaba16witch_book_bytesE:\n.incbin "../assets/trial/book.bin"\n')
    report=dict(shared_raw_bytes=len(common),rom_payload_bytes=len(blob),new_images=len(entries),cached_images=cached,
                new_evidence_images=0,large_initials=len(glyphs))
    write_changed(generated_path('reports/book-art.json'),json.dumps(report,indent=2)+'\n')
    print(report)


if __name__=='__main__':main()
