"""Native 240x160 startup notice design, using the project's pixel fonts."""
from build_paths import generated_path
from pathlib import Path
import gzip,json
from PIL import Image,ImageDraw
from font import read_font
GBA=Path(__file__).resolve().parents[1]
OUT=generated_path('design/warning-screen')
# Three groups, with complete phrases and centered rights-holder lines.
LINES=[
 (36,'本作为《魔法少女的魔女审判》'),
 (49,'非官方同人移植，与原作方无关。'),
 (68,'文字、图像和音乐等素材的相关'),
 (81,'权利归 Acacia / Re,AER 和'),
 (94,'CIRCLE LINE GAMES 等权利人所有。'),
 (113,'本移植仅供研究GBA开发'),
 (126,'和学习交流使用。'),
 (145,'请支持并购买正版游戏。'),
]
BODY=[text for _,text in LINES]

def render():
 font=read_font();im=Image.new('RGB',(240,160),(16,16,24));draw=ImageDraw.Draw(im)
 # Unifont's native 8x16 ASCII title. No antialiasing or runtime image processing.
 unifont={}
 with gzip.open(GBA/'assets/unifont-17.0.03.hex.gz','rt') as source:
  for line in source:
   code,raw=line.strip().split(':')
   if chr(int(code,16)) in 'WARNING':unifont[int(code,16)]=bytes.fromhex(raw)
 for index,char in enumerate('WARNING'):
  for y,bits in enumerate(unifont[ord(char)]):
   for x in range(8):
    if bits&(1<<(7-x)):draw.point((92+index*8+x,4+y),fill=(240,72,88))
 draw.line((12,25,227,25),fill=(88,40,48))
 for line_y,line in LINES:
  width=sum(6 if ord(c)<128 else 12 for c in line)
  assert width<=216
  at=(240-width)//2
  for char in line:
   assert ord(char) in font,char
   for y,bits in enumerate(font[ord(char)]):
    for x in range(6 if ord(char)<128 else 12):
     if bits&(1<<(11-x)):draw.point((at+x,line_y-4+y),fill=(216,216,208))
   at+=6 if ord(char)<128 else 12
 return im,unifont

def main():
 OUT.mkdir(parents=True,exist_ok=True);im,unifont=render()
 im.save(OUT/'warning-native.png');im.resize((960,640),Image.Resampling.NEAREST).save(OUT/'warning-preview.png')
 (OUT/'copy.txt').write_text('WARNING\n\n'+'\n'.join(BODY)+'\n')
 # The ROM draws these same rows with its existing canvas, not a stored full-screen bitmap.
 (GBA/'src/warning_screen_data.h').write_text('#pragma once\n#include <stdint.h>\nnamespace manosaba {\nstruct warning_line {const char* text;uint8_t x,y;};\nextern const warning_line warning_lines[8];\nextern const uint16_t warning_header[7][16];\n}\n')
 cpp=['// Generated by tools/warning_screen_mockup.py.','#include "warning_screen_data.h"','namespace manosaba {','const warning_line warning_lines[8]={']
 for y,line in LINES:
  width=sum(6 if ord(c)<128 else 12 for c in line)
  cpp.append('{'+json.dumps(line,ensure_ascii=False)+','+str((240-width)//2)+','+str(y-4)+'},')
 cpp+=['};','const uint16_t warning_header[7][16]={']
 for char in 'WARNING':cpp.append('{'+','.join(str(v<<8) for v in unifont[ord(char)])+'},')
 cpp+=['};','}']
 (GBA/'src/warning_screen_data.cpp').write_text('\n'.join(cpp)+'\n')
 print(OUT)
if __name__=='__main__':main()
