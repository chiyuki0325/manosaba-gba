#!/usr/bin/env python3
"""Reflow source dialogue for GBA text boxes without changing source scripts.

Original breaks after overflowing source lines are soft; fitting lines keep their breaks.
The compiler and source reference interpreter use this exact presentation format.
"""
from build_paths import generated_path
from pathlib import Path
import argparse
from functools import reduce
import html
import json
import re
from graphical_story import SCRIPT as GRAPHICAL_SCRIPT

GBA = Path(__file__).resolve().parents[1]
ROOT = GBA.parent
CONFIG = json.loads((GBA / 'assets/text-layout.json').read_text())
PROFILES = CONFIG['profiles']
NO_START = set('，。！？：；、）》】〕〉」』”’％%)]}.,!?;:…—～\ue000\ue001\ue002\u2060')
NO_END = set('（《【〔〈「『“‘([{\u2060')
INLINE = re.compile(r'\[(?:wait|w|i|b|s|speed|shake|reset|char|back|sfx|voice|hide)[^\]]*\]')


def source_paragraphs(source):
    # A newline immediately after <br> is the same original line boundary.
    text = re.sub(r'<br\s*/?>[ \t]*(?:\r?\n)?', '\n', source, flags=re.I)
    text = html.unescape(INLINE.sub('', re.sub(r'<[^>]*>', '', text)))
    text = text.replace('\r\n', '\n').replace('\r', '\n')
    return [[line.strip(' \t\u3000') for line in paragraph.split('\n') if line.strip(' \t\u3000')]
            for paragraph in re.split(r'\n[ \t\u3000]*\n+', text) if paragraph.strip()]


def join_source(left, right):
    if left and right and left[-1].isascii() and left[-1].isalnum() and right[0].isascii() and right[0].isalnum():
        return left+' '+right
    return left+right


def clean_text(source):
    # Non-dialogue labels have no screen-specific wrapping policy.
    return '\n\n'.join(reduce(join_source, paragraph, '')
                       for paragraph in source_paragraphs(source))


def pixel_width(text):
    return sum(0 if c=='\u2060' else 13 if '\ue000'<=c<='\ue004' else CONFIG['ascii_width'] if ord(c) < 128 else CONFIG['wide_width'] for c in text)


def latin_word(char):
    return char.isascii() and (char.isalnum() or char == '_')


def legal_boundary(text, at):
    return (text[at] not in NO_START and text[at-1] not in NO_END and
            not (text[at] == text[at-1] and text[at] in '…—'))


def wrap_paragraph(text, width):
    lines = []
    while text:
        if pixel_width(text) <= width:
            lines.append(text)
            break
        end, used = 0, 0
        while end < len(text):
            advance = pixel_width(text[end])
            if used + advance > width:
                break
            used += advance
            end += 1
        if not end:
            raise ValueError(f'Text box is narrower than one glyph: {width}')
        fit = end
        # Keep an ASCII word together when it can fit on a fresh line.
        if latin_word(text[end-1]) and latin_word(text[end]):
            word_start = end-1
            while word_start and latin_word(text[word_start-1]):
                word_start -= 1
            word_end = end
            while word_end < len(text) and latin_word(text[word_end]):
                word_end += 1
            if word_start and pixel_width(text[word_start:word_end]) <= width:
                end = word_start
        while end and not legal_boundary(text, end):
            end -= 1
        if not end:
            # A token longer than the box still has to make forward progress.
            end = fit
        lines.append(text[:end].rstrip(' '))
        text = text[end:].lstrip(' ')
    return '\n'.join(lines)


def reflow(source, width):
    if width < CONFIG['wide_width']:
        raise ValueError('Text box must fit at least one wide glyph')
    paragraphs = []
    for original_lines in source_paragraphs(source):
        lines, pending = [], ''
        for original in original_lines:
            pending = join_source(pending, original)
            if pixel_width(original) <= width:
                lines.append(wrap_paragraph(pending,width))
                pending = ''
        if pending:
            lines.append(wrap_paragraph(pending,width))
        paragraphs.append('\n'.join(lines))
    return '\n\n'.join(paragraphs)


_catalog_path=GBA/'assets/graphics/catalog.json'
_GRAPHICAL_SCRIPTS={entry['path'] for entry in json.loads(_catalog_path.read_text())['chapters']} if _catalog_path.exists() else {GRAPHICAL_SCRIPT}


def profile_for(script):
    return 'graphical' if script in _GRAPHICAL_SCRIPTS else 'story'


def dialogue_text(source, script):
    profile = PROFILES[profile_for(script)]
    return reflow(source, profile['right']-profile['left'])


def write_runtime_header():
    lines = ['// Generated by tools/story_layout.py from assets/text-layout.json.',
             '#ifndef STORY_LAYOUT_H', '#define STORY_LAYOUT_H', 'namespace manosaba {',
             'struct dialogue_layout { int left, top, right, bottom; };']
    lines.append(f'constexpr char graphical_story_path[] = {json.dumps(GRAPHICAL_SCRIPT)};')
    for name in ('ascii_width', 'wide_width', 'line_height'):
        lines.append(f'constexpr int dialogue_{name} = {CONFIG[name]};')
    for name, values in PROFILES.items():
        numbers = ','.join(str(values[k]) for k in ('left', 'top', 'right', 'bottom'))
        lines.append(f'constexpr dialogue_layout {name}_dialogue = {{{numbers}}};')
    lines += ['}', '#endif', '']
    path = GBA / 'src/story_layout.h'
    content = '\n'.join(lines)
    if not path.exists() or path.read_text() != content:
        path.write_text(content)


def source_paths():
    return [p for p in sorted((ROOT / 'story/zh-Hans').glob('Act*/*.json'))
            if re.search(r'_(Adv|Bad)\d+$', p.stem)]


def catalog():
    records = []
    for path in source_paths():
        doc = json.loads(path.read_text())
        for event in doc['events']:
            if event['op'] == 'PrintTextModified':
                source = event['params']['Text']
                records.append(dict(script=doc['path'], line=event['line'],
                                    text_ids=event.get('text_ids', {}).get('Text', []),
                                    profile=profile_for(doc['path']), source=source,
                                    text=dialogue_text(source, doc['path'])))
    return records


def report(records):
    profiles = {}
    for name, box in PROFILES.items():
        selected = [r for r in records if r['profile'] == name]
        profiles[name] = dict(box, width=box['right']-box['left'],
                             lines_per_page=1+(box['bottom']-box['top']-CONFIG['wide_width'])//CONFIG['line_height'],
                             dialogue_count=len(selected),
                             max_line_pixels=max((pixel_width(line) for r in selected for line in r['text'].split('\n')), default=0))
    return dict(scripts=len(source_paths()), scripts_with_dialogue=len({r['script'] for r in records}), dialogue_count=len(records),
                source_soft_breaks=sum(len(re.findall(r'<br\s*/?>', r['source'], re.I)) for r in records),
                changed_dialogues=sum(r['source'] != r['text'] for r in records),
                max_utf8_bytes=max((len(r['text'].encode())+1 for r in records), default=0),
                profiles=profiles)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--text', help='Preview one original dialogue (including <br>)')
    parser.add_argument('--width', type=int, default=198, help='Text width in pixels')
    parser.add_argument('--output', type=Path, help='Write readable reflowed story records as JSON')
    args = parser.parse_args()
    if args.text is not None:
        print(reflow(args.text, args.width))
        return
    records = catalog()
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(records, ensure_ascii=False, indent=2)+'\n')
    result = report(records)
    (generated_path('reports/text-layout.json')).write_text(json.dumps(result, ensure_ascii=False, indent=2)+'\n')
    write_runtime_header()
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
